/// 端末スリープ中も進み続ける単調時計の現在値を返す境界です。
///
/// 壁時計の変更に影響されず、端末スリープ中の経過も含めて単調増加する値を返します。
/// 応答途絶・猶予・チャンクcommitの経過判定に使います。
nonisolated protocol MonotonicClockPort: Sendable {
    /// 単調時計の現在値をナノ秒で返します。
    ///
    /// 責務: スリープ中の経過を含む単調時計の現在値を1回読み取ります。
    /// - Returns: 起点からのナノ秒。同じ端末の起動中は呼び出しごとに減少しません。
    func nowNanoseconds() -> UInt64
}
