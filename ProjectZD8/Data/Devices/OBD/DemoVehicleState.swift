/// デモ走行のある時刻における車両状態(物理値)です。
nonisolated struct DemoVehicleState: Equatable, Sendable {
    /// エンジン回転数 [rpm]。
    let engineSpeed: Double
    /// 車速 [km/h]。
    let vehicleSpeed: Double
    /// 計算エンジン負荷 [%]。
    let engineLoad: Double
    /// スロットル開度 [%]。
    let throttle: Double
    /// 冷却水温 [°C]。
    let coolantTemperature: Double
    /// 吸気温 [°C]。
    let intakeTemperature: Double
    /// 外気温 [°C]。
    let ambientTemperature: Double
    /// エンジン油温 [°C]。
    let oilTemperature: Double
    /// ATF油温 [°C]。
    let transmissionFluidTemperature: Double
    /// 吸気管圧力 [kPa]。
    let manifoldPressure: Double
    /// 吸入空気量 [g/s]。
    let massAirFlow: Double
    /// 点火時期 [°]。
    let timingAdvance: Double
    /// 短期燃料補正 [%]。
    let shortTermFuelTrim: Double
    /// 長期燃料補正 [%]。
    let longTermFuelTrim: Double
    /// 燃料残量 [%]。
    let fuelLevel: Double
    /// 制御モジュール電圧 [V]。
    let moduleVoltage: Double
    /// エンジン始動後の経過時間 [s]。
    let runTime: Double
    /// 走行距離計 [km]。
    let odometer: Double
}
