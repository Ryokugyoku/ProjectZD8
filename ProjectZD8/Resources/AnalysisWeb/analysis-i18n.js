export const LANGUAGES = ['ja', 'en', 'es'];

/** Dictionary per language: { ja: { key: text }, ... }. */
export const DICTIONARY = Object.fromEntries(LANGUAGES.map((lang, i) => [lang, Object.fromEntries(Object.entries(ENTRIES).map(([key, texts]) => [key, texts[i]]))]));

/** Maps a BCP-47 tag (e.g. "ja-JP") to a supported language, defaulting to English. */
export function resolveLanguage(tag) {
  const base = String(tag || '').toLowerCase().split(/[-_]/)[0];
  return LANGUAGES.includes(base) ? base : 'en';
}

/** Returns t(key, params): text in the language, falling back to English, then to the key itself. */
export function makeTranslator(lang) {
  const table = DICTIONARY[lang] || DICTIONARY.en;
  return (key, params) => {
    const text = table[key] ?? DICTIONARY.en[key];
    if (text === undefined) return key;
    return params ? text.replace(/\{(\w+)\}/g, (_, name) => (name in params ? String(params[name]) : `{${name}}`)) : text;
  };
}
